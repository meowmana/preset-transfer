// 跑法：node tests/worldbook-stitch-edit.browser.mjs —— 要本机测试酒馆(8123)、预设“缝好测试”、世界书 Eldoria；会改 Eldoria 第一条再改回去，跑前自己备份
import { createRequire } from 'module';
const puppeteer = createRequire('/home/admin/scripts/paper-anim/web/')('puppeteer-core');
const browser = await puppeteer.launch({ executablePath: '/usr/local/bin/google-chrome', headless: 'new', args: ['--no-sandbox'] });
const page = await browser.newPage();
page.on('dialog', (d) => d.accept());
await page.setViewport({ width: 412, height: 900, isMobile: true });
await page.goto('http://127.0.0.1:8123/', { waitUntil: 'networkidle2', timeout: 90000 });
await page.waitForFunction(() => window.PresetTransfer, { timeout: 60000 });
await new Promise((r) => setTimeout(r, 3000));
await page.evaluate(() => (window.PresetTransfer.MainUI?.createTransferUI || window.PresetTransfer.createTransferUI)?.());
await new Promise((r) => setTimeout(r, 3000));
const r = await page.evaluate(async () => {
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  const s = document.querySelector('#left-preset');
  $(s).val([...s.options].find((o) => o.textContent.trim() === '缝好测试').value).trigger('change');
  $('#right-preset').val('').trigger('change');
  await sleep(1500);
  [...document.querySelectorAll('button')].find((b) => b.textContent.trim() === '加载条目')?.click();
  await sleep(4000);
  document.querySelector('#pt-stitch-from-worldbook').click();
  await sleep(2000);
  $('#pt-wb-stitch-dialog .pt-wb-stitch-book').val('Eldoria').trigger('change');
  await sleep(2000);
  const pick1 = document.querySelector('#pt-wb-stitch-dialog .pt-wb-stitch-pick[data-index="1"]');
  pick1.click();
  const edit0 = document.querySelector('#pt-wb-stitch-dialog .pt-wb-stitch-edit[data-index="0"]');
  edit0.click();
  await sleep(1500);
  const box = document.querySelector('#pt-wi-content');
  const opened = { modal: !!box, panelHidden: getComputedStyle(document.querySelector('#pt-wb-stitch-dialog')).display === 'none', check0: document.querySelector('#pt-wb-stitch-dialog .pt-wb-stitch-pick[data-index="0"]').checked, full: box?.value.length };
  const orig = box.value;
  $(box).val(orig + ' 改过了').trigger('input');
  document.querySelector('#pt-wi-save').click();
  await sleep(4000);
  const preview0 = document.querySelector('#pt-wb-stitch-dialog .pt-wb-stitch-pick[data-index="0"]').closest('label').textContent;
  const after = { modalGone: !document.querySelector('#pt-worldbook-edit-modal'), panelBack: getComputedStyle(document.querySelector('#pt-wb-stitch-dialog')).display !== 'none', keep1: document.querySelector('#pt-wb-stitch-dialog .pt-wb-stitch-pick[data-index="1"]').checked, armed: window.transferMode?.fromSide === 'worldbook' };
  document.querySelector('#pt-wb-stitch-dialog .pt-wb-stitch-edit[data-index="0"]').click();
  await sleep(1500);
  const reread = document.querySelector('#pt-wi-content').value.endsWith(' 改过了');
  $('#pt-wi-content').val(orig);
  document.querySelector('#pt-wi-save').click();
  await sleep(4000);
  return { opened, after, reread, origLen: orig.length };
});
await page.screenshot({ path: process.env.SHOT || '/tmp/wb-stitch-edit.png' });
console.log(JSON.stringify(r));
await browser.close();
const ok = r.opened.modal && r.opened.panelHidden && !r.opened.check0 && r.opened.full === r.origLen && r.after.modalGone && r.after.panelBack && r.after.keep1 && r.reread;
if (!ok) { console.error('世界书缝入面板：编辑按钮没打开、没把面板让开，或改完没读回'); process.exit(1); }
console.log('worldbook-stitch-edit: 编辑打开、改完读回、勾选保住，过');
